class TiffinSubscriptionFormTransation {
  String? name;
  String? code;
  String? nativeName;
  String? title;
  String? shortDescription;

  TiffinSubscriptionFormTransation({this.name, this.code, this.nativeName, this.title, this.shortDescription});

  TiffinSubscriptionFormTransation.fromJson(Map<String, dynamic> json) {
    name = json['name'];
    code = json['code'];
    nativeName = json['nativeName'];
    title = json['title'];
    shortDescription = json['shortDescription'];
  }

  Map<String, dynamic> toJson() {
    final Map<String, dynamic> data = <String, dynamic>{};
    data['name'] = name;
    data['code'] = code;
    data['nativeName'] = nativeName;
    data['title'] = title;
    data['shortDescription'] = shortDescription;
    return data;
  }
}

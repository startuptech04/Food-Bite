class CustomSubCategoryFormTranslations {
  String? name;
  String? code;
  String? nativeName;
  String? value;

  CustomSubCategoryFormTranslations({this.name, this.code, this.nativeName, this.value});

  CustomSubCategoryFormTranslations.fromJson(Map<String, dynamic> json) {
    name = json['name'];
    code = json['code'];
    nativeName = json['nativeName'];
    value = json['value'];
  }

  Map<String, dynamic> toJson() {
    final Map<String, dynamic> data = <String, dynamic>{};
    data['name'] = name;
    data['code'] = code;
    data['nativeName'] = nativeName;
    data['value'] = value;
    return data;
  }
}

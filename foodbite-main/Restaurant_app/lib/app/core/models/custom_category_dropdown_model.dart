class CustomCategoryDropdownInterfaceModel {
  bool? value;
  String? label;

  CustomCategoryDropdownInterfaceModel({this.value, this.label});

  CustomCategoryDropdownInterfaceModel.fromJson(Map<String, dynamic> json) {
    value = json['value'];
    label = json['label'];
  }

  Map<String, dynamic> toJson() {
    final Map<String, dynamic> data = <String, dynamic>{};
    data['value'] = value;
    data['label'] = label;
    return data;
  }
}

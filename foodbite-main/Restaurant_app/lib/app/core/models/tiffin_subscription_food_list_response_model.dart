class TiffinSubscriptionFoodListResponseModel {
  List<TiffinSubscriptionFoodConfigModel>? foods;
  final String locale;
  TiffinSubscriptionFoodListResponseModel({this.foods, required this.locale});

  TiffinSubscriptionFoodListResponseModel.fromJson(Map<String, dynamic> json, this.locale) {
    if (json['foods'] != null) {
      foods = <TiffinSubscriptionFoodConfigModel>[];
      json['foods'].forEach((v) {
        foods!.add(TiffinSubscriptionFoodConfigModel.fromJson(v, locale));
      });
    }
  }

  Map<String, dynamic> toJson() {
    final Map<String, dynamic> data = <String, dynamic>{};
    if (foods != null) {
      data['foods'] = foods!.map((v) => v.toJson()).toList();
    }
    return data;
  }
}

class TiffinSubscriptionFoodConfigModel {
  String? name;
  String? image;
  List<AddonsConfigModel>? addons;
  String? discountType;
  List<VariationConfigModel>? variations;
  List<FoodTranslations>? translations;
  String? id;
  double? price;
  double? discount;
  final String locale;
  TiffinSubscriptionFoodConfigModel({this.name, this.image, this.addons, this.discountType, this.variations, this.translations, this.id, this.price, this.discount, required this.locale});

  TiffinSubscriptionFoodConfigModel.fromJson(Map<String, dynamic> json, this.locale) {
    name = json['name'];
    image = json['image'];
    if (json['addons'] != null) {
      addons = <AddonsConfigModel>[];
      json['addons'].forEach((v) {
        addons!.add(AddonsConfigModel.fromJson(v, locale));
      });
    } else {
      addons = [];
    }
    discountType = json['discountType'];
    if (json['variations'] != null) {
      variations = <VariationConfigModel>[];
      json['variations'].forEach((v) {
        variations!.add(VariationConfigModel.fromJson(v));
      });
    } else {
      variations = [];
    }
    if (json['translations'] != null) {
      translations = <FoodTranslations>[];
      json['translations'].forEach((v) {
        translations!.add(FoodTranslations.fromJson(v));
      });
      if (locale.isNotEmpty && translations!.isNotEmpty) {
        final int localeIndex = translations!.indexWhere((tLocale) => tLocale.code! == locale);
        if (localeIndex != -1) {
          if (translations![localeIndex].title!.isNotEmpty) {
            name = translations![localeIndex].title!;
          }
        }
      }
    } else {
      translations = [];
    }
    id = json['id'];
    if (json['price'] != null && json['price'] != '') {
      price = double.parse(json['price'].toString());
    } else {
      price = 0;
    }
    if (json['discount'] != null && json['discount'] != '') {
      discount = double.parse(json['discount'].toString());
    } else {
      discount = 0;
    }
  }

  Map<String, dynamic> toJson() {
    final Map<String, dynamic> data = <String, dynamic>{};
    data['name'] = name;
    data['image'] = image;
    if (addons != null) {
      data['addons'] = addons!.map((v) => v.toJson()).toList();
    }
    data['discountType'] = discountType;
    if (variations != null) {
      data['variations'] = variations!.map((v) => v.toJson()).toList();
    }
    if (translations != null) {
      data['translations'] = translations!.map((v) => v.toJson()).toList();
    }
    data['id'] = id;
    data['price'] = price;
    data['discount'] = discount;
    return data;
  }
}

class AddonsConfigModel {
  String? name;
  List<Translations>? translations;
  String? id;
  final String locale;
  AddonsConfigModel({this.name, this.translations, this.id, required this.locale});

  AddonsConfigModel.fromJson(Map<String, dynamic> json, this.locale) {
    name = json['name'];
    if (json['translations'] != null) {
      translations = <Translations>[];
      json['translations'].forEach((v) {
        translations!.add(Translations.fromJson(v));
      });
      if (locale.isNotEmpty && translations!.isNotEmpty) {
        final int localeIndex = translations!.indexWhere((tLocale) => tLocale.code! == locale);
        if (localeIndex != -1) {
          if (translations![localeIndex].value!.isNotEmpty) {
            name = translations![localeIndex].value!;
          }
        }
      }
    } else {
      translations = [];
    }
    id = json['id'];
  }

  Map<String, dynamic> toJson() {
    final Map<String, dynamic> data = <String, dynamic>{};
    data['name'] = name;
    if (translations != null) {
      data['translations'] = translations!.map((v) => v.toJson()).toList();
    }
    data['id'] = id;
    return data;
  }
}


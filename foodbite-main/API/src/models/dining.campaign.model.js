const mongoose = require('mongoose');
const { toJSON, paginate } = require('./plugins');

const diningCampaignSchema = mongoose.Schema(
  {
    title: {
      type: String,
      required: true,
      trim: true,
    },
    shortDescription: {
      type: String,
      required: true,
      trim: true,
    },
    city: {
      type: mongoose.SchemaTypes.ObjectId,
      ref: 'City',
      required: true,
    },
    restaurant: [
      {
        type: mongoose.SchemaTypes.ObjectId,
        ref: 'Restaurant',
        required: true,
      },
    ],
    image: {
      type: String,
      required: true,
    },
    startDate: {
      type: Date,
      required: true,
    },
    endDate: {
      type: Date,
      required: true,
    },
    startTime: {
      type: String,
      required: true,
    },
    endTime: {
      type: String,
      required: true,
    },
    translations: {
      type: Array,
      default: [],
    },
    status: {
      type: Boolean,
      default: true,
    },
  },
  {
    timestamps: true,
  }
);

// add plugin that converts mongoose to json & convert to unique slug
diningCampaignSchema.plugin(toJSON);
diningCampaignSchema.plugin(paginate);

/**
 * @typedef DiningCampaign
 */
const DiningCampaign = mongoose.model('DiningCampaign', diningCampaignSchema);

module.exports = DiningCampaign;
